-- 한 단계의 8개 쿼리를 EXPLAIN (ANALYZE, BUFFERS)로 각각 3번 실행하고, 실행 시간이 가장 짧은 회차를 한 표로 보여준다.
-- (1회차는 캐시가 차가울 수 있어 best-of-3. 버퍼는 그 회차의 값)
CREATE OR REPLACE FUNCTION perf_test.run_stage(p_form text)
RETURNS TABLE(query_name text, scan_nodes text, index_names text, exec_ms numeric, shared_hit bigint, shared_read bigint)
LANGUAGE plpgsql AS $fn$
DECLARE
    r record; jj json; best jsonb; cur jsonb; t numeric; bt numeric; i int;
BEGIN
    FOR r IN SELECT q.name, q.sql FROM perf_test.bench_query q WHERE q.form = p_form ORDER BY q.name LOOP
        best := NULL; bt := NULL;
        FOR i IN 1..3 LOOP
            EXECUTE 'EXPLAIN (ANALYZE, BUFFERS, FORMAT JSON) ' || r.sql INTO jj;
            cur := jj::jsonb;
            t := (cur->0->>'Execution Time')::numeric;
            IF bt IS NULL OR t < bt THEN bt := t; best := cur; END IF;
        END LOOP;
        query_name := r.name;
        scan_nodes := (SELECT string_agg(DISTINCT x #>> '{}', ', ')
                       FROM jsonb_path_query(best, 'strict $.**."Node Type" ? (@ like_regex "Scan")') x);
        index_names := (SELECT string_agg(DISTINCT x #>> '{}', ', ')
                        FROM jsonb_path_query(best, 'strict $.**."Index Name"') x);
        exec_ms := bt;
        shared_hit := COALESCE((best->0->'Plan'->>'Shared Hit Blocks')::bigint, 0);
        shared_read := COALESCE((best->0->'Plan'->>'Shared Read Blocks')::bigint, 0);
        RETURN NEXT;
    END LOOP;
END $fn$;

-- 개별 쿼리의 전체 실행 계획(텍스트)이 필요할 때: SELECT * FROM perf_test.explain_text('q1_findActiveDays','range');
CREATE OR REPLACE FUNCTION perf_test.explain_text(p_name text, p_form text)
RETURNS SETOF text LANGUAGE plpgsql AS $fn$
DECLARE s text;
BEGIN
    SELECT sql INTO s FROM perf_test.bench_query WHERE name = p_name AND form = p_form;
    RETURN QUERY EXECUTE 'EXPLAIN (ANALYZE, BUFFERS) ' || s;
END $fn$;

